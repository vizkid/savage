'use strict';

// Generates ../vector-template.js from a captured single-freeform dump.
// Usage: node make-template.js <freeform-dump.json>
// Sanitizes: strips clip-id + edrk/edi, patches shape type to 138, zeroes the
// transform, and tokenizes the html guid. Re-run against any fresh capture if
// Slides ever rejects the shipped template.

const fs = require('fs');
const path = require('path');

const TYPE = 'application/x-vnd.google-docs-drawings-object+wrapped';

const dump = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const wrapper = JSON.parse(dump[TYPE]);
const data = JSON.parse(wrapper.data);

const shapeCmd = data.resolved.find((c) => c[0] === 3);
if (!shapeCmd || data.resolved.length !== 1) {
  console.error('dump must contain exactly one freeform shape command');
  process.exit(1);
}
shapeCmd[1] = 'TEMPLATE_ID';
shapeCmd[2] = 138; // 154 spline-smooths op-1 chains (FINDINGS)
shapeCmd[3] = [1, 0, 0, 1, 0, 0];

const skeleton = {};
for (const [k, v] of Object.entries(data)) {
  if (k !== 'resolved' && k !== 'unresolved') skeleton[k] = v;
}

const template = {
  envelope: { dih: wrapper.dih, ds: wrapper.ds, cses: wrapper.cses, sm: wrapper.sm },
  dataSkeleton: skeleton,
  shapeCmd,
  html: (dump['text/html'] || '').replace(
    /docs-internal-guid-[0-9a-f-]+/g,
    'docs-internal-guid-TEMPLATE'
  ),
};

const out = `'use strict';

// Sanitized capture of a single Slides freeform shape (generated by
// research/make-template.js — do not hand-edit; regenerate from a fresh
// capture instead). The converter morphs this template because from-scratch
// payload assembly crashes the Slides editor (research/FINDINGS.md,
// "From-scratch synthesis"). clip-id and server keys are stripped; the dih is
// proven to paste cross-deck. Shape ids and the html guid are randomized at
// every call by vectorize.js.

const VECTOR_TEMPLATE = ${JSON.stringify(template, null, 2)};
`;

const dest = path.join(__dirname, '..', 'vector-template.js');
fs.writeFileSync(dest, out);
console.log('wrote', dest);
